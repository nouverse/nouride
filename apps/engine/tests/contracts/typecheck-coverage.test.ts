/**
 * Every TypeScript file in this repository is in a project `lint:types` checks — or in one it names as not its own.
 *
 * `check-types` ran a hand-kept list of fifteen tsconfigs, and the files outside them were typechecked by nothing:
 * `bun test` and `bun run` strip types without reading them. The dashboard's tests held a fixture still shaped like a
 * person before `id` became `key`, the WhatsApp bridge's tests imported a shim no type described, and `check-arch.ts`
 * passed `string | undefined` where a string belonged. Each passed. The list is found now (`publicProjects`), and this
 * asks the property that list exists for, file by file: a test file, a script or a package nobody thought to add a
 * tsconfig for fails here, with its path.
 */

import { describe, expect, test } from "bun:test";
import { readdirSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";
import { NOT_FOR_TSC, publicProjects } from "../../../../scripts/lint-sources.ts";

const ROOT = join(import.meta.dir, "../../../..");

/** The files one project's tsconfig takes in — its `include`, `files` and `exclude`, resolved as `tsc` resolves them. */
function filesOf(project: string): string[] {
  const parsed = ts.getParsedCommandLineOfConfigFile(join(ROOT, project, "tsconfig.json"), {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (diagnostic) => {
      throw new Error(`${project}: ${ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")}`);
    },
  });
  return parsed?.fileNames ?? [];
}

/** Every TypeScript source under `dir`, relative to the root — what is installed, built or generated by a tool left out. */
function sources(dir: string): string[] {
  return readdirSync(join(ROOT, dir), { withFileTypes: true }).flatMap((entry) => {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) {
      return entry.name === "node_modules" || entry.name === "dist" || entry.name.startsWith(".") ? [] : sources(path);
    }
    return /\.(ts|tsx|mts|cts)$/.test(entry.name) ? [path] : [];
  });
}

describe("lint:types", () => {
  test("covers every TypeScript file, or the project it is in says why not", () => {
    const checked = publicProjects(ROOT).filter((project) => !(project in NOT_FOR_TSC));
    const covered = new Set(checked.flatMap(filesOf).map((file) => file.slice(ROOT.length + 1)));
    const excused = Object.keys(NOT_FOR_TSC).map((project) => `${project}/`);

    const uncovered = ["apps", "packages", "scripts"].flatMap(sources).filter(
      (file) => !covered.has(file) && !excused.some((dir) => file.startsWith(dir)),
    );
    expect(uncovered).toEqual([]);
  });

  test("finds the projects the hand-kept list left out", () => {
    const projects = publicProjects(ROOT);
    for (const project of ["apps/dashboard/tests", "apps/site/scripts", "scripts", "packages/wa-bridge"]) {
      expect(projects).toContain(project);
    }
  });
});
