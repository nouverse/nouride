/**
 * Fold every migration into one baseline file, and prove the two produce the same schema.
 *
 * Run by hand, when an upgrade floor means no install in the field is at a version below the chain's last — `bun run
 * scripts/squash-migrations.ts` to compare, `--write` to write the baseline (`069_baseline.sql`, the last time),
 * `--check` to compare the file already written (after its comments were added by hand) against the chain. It is not
 * part of any build. Run it before the files it folds are deleted: the chain is what it compares against.
 *
 * ## What it does not do
 *
 * It does not let a database at an intermediate version reach the baseline. That is the whole cost of a squash: the
 * steps are gone. So it is done only when every install has crossed a floor at the chain's last version — 2026-09-09
 * when the only two installs were both at 32, 2026-10-24 when 0.8.0 refused every install 0.7.28 had not run on, and
 * 2026-10-26 when every release after 0.8.0 refused every install 0.8.0 had not run on.
 *
 * It does not keep a migration's header comment either. The baseline is rendered from `sqlite_master`, which holds
 * the statements and the comments inside them and nothing else. Why a table exists is written between the statements
 * by hand after `--write`, or in the `*.store.ts` that owns the table, and `--check` confirms the file still
 * reproduces the chain.
 *
 * ## The fingerprint it prints
 *
 * A database the chain built holds the chain's fingerprint (`schemaFingerprint` in `apps/engine/src/db/index.ts`),
 * and the baseline must be read as that same schema — so the fingerprint is printed here, and the baseline's entry in
 * `apps/engine/src/db/migrations.ts` states it rather than hashing its own text.
 *
 * ## Why the baseline keeps the version it replaces
 *
 * Version numbers are the *only* thing that decides what a database still needs: a baseline at version 1 would leave
 * every install already at the chain's last with `pending = []` forever, so a later migration would never apply to
 * them. The baseline is that version because that is what it is.
 */

import { Database } from "bun:sqlite";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MIGRATIONS } from "../apps/engine/src/db/migrations.ts";
import { schemaFingerprint } from "../apps/engine/src/db/index.ts";

interface Entry {
  type: string;
  name: string;
  sql: string;
}

/**
 * Every object the schema defines, in a deterministic order.
 *
 * `sqlite_%` is SQLite's own — `sqlite_sequence` and the autoindexes behind `PRIMARY KEY` — and an FTS5 table's
 * shadow tables (`memory_fts_data`, `_idx`, …) are the module's: both are made by the statements below, not by
 * statements of their own. Emitting them would produce a file SQLite refuses.
 */
function schemaOf(db: Database): Entry[] {
  const entries = db
    .prepare(
      `SELECT type, name, sql FROM sqlite_master
        WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
        ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'view' THEN 1 WHEN 'index' THEN 2 ELSE 3 END, name`,
    )
    .all() as Entry[];
  // Exactly FTS5's five, not every name the virtual table's starts: `memory_fts_items` is a table of the schema's own.
  const shadows = new Set(
    entries
      .filter((entry) => /^CREATE VIRTUAL TABLE/i.test(entry.sql))
      .flatMap((entry) => ["data", "idx", "content", "docsize", "config"].map((suffix) => `${entry.name}_${suffix}`)),
  );
  return entries.filter((entry) => !(entry.type === "table" && shadows.has(entry.name)));
}

function applyChain(): Database {
  const db = new Database(":memory:");
  db.exec("PRAGMA foreign_keys = ON");
  for (const migration of [...MIGRATIONS].sort((a, b) => a.version - b.version)) {
    db.transaction(() => {
      db.exec(migration.sql);
      db.exec(`PRAGMA user_version = ${migration.version}`);
    })();
  }
  return db;
}

/** Whitespace differs between a hand-written statement and the one SQLite stores; nothing else may. */
function normalise(sql: string): string {
  return sql.replace(/\s+/g, " ").trim();
}

function render(entries: Entry[], version: number): string {
  const header = `-- The schema the chain left: every migration up to ${version}, folded into one file.
--
-- Generated by \`scripts/squash-migrations.ts\` from the chain it replaces, and verified against it: applying this
-- file produces the same \`sqlite_master\` as applying the chain.
--
-- **This file is applied and never edited.** It is schema version ${version}, so a database already at ${version}
-- needs nothing; the next change is \`0${version + 1}_*.sql\`.
`;
  const body = entries.map((entry) => `${entry.sql.trim()};`).join("\n\n");
  return `${header}\n${body}\n`;
}

function differencesBetween(chainSchema: Entry[], text: string): string[] {
  const replayed = new Database(":memory:");
  replayed.exec("PRAGMA foreign_keys = ON");
  replayed.exec(text);
  const replayedSchema = schemaOf(replayed);
  const differences: string[] = [];
  const names = new Set([...chainSchema, ...replayedSchema].map((e) => `${e.type}:${e.name}`));
  for (const key of [...names].sort()) {
    const before = chainSchema.find((e) => `${e.type}:${e.name}` === key);
    const after = replayedSchema.find((e) => `${e.type}:${e.name}` === key);
    if (!before) differences.push(`only in the baseline: ${key}`);
    else if (!after) differences.push(`only in the chain:    ${key}`);
    else if (normalise(before.sql) !== normalise(after.sql)) {
      differences.push(`differs: ${key}\n    chain:    ${normalise(before.sql)}\n    baseline: ${normalise(after.sql)}`);
    }
  }
  return differences;
}

const chain = applyChain();
const chainSchema = schemaOf(chain);
const version = (chain.prepare("PRAGMA user_version").get() as { user_version: number }).user_version;
const target = join(import.meta.dir, "..", "apps", "engine", "src", "db", "migrations", `${String(version).padStart(3, "0")}_baseline.sql`);

// A new database is made by the baseline alone, so the chain must leave no rows a new database would need.
const seeded = chainSchema
  .filter((entry) => entry.type === "table" && !/^CREATE VIRTUAL TABLE/i.test(entry.sql))
  .filter((entry) => (chain.prepare(`SELECT COUNT(*) AS n FROM "${entry.name}"`).get() as { n: number }).n > 0)
  .map((entry) => entry.name);
if (seeded.length > 0) {
  console.error(`✗ the chain leaves rows in a new database, which a baseline would not: ${seeded.join(", ")}`);
  process.exit(1);
}

const check = process.argv.includes("--check");
const baseline = check ? readFileSync(target, "utf8") : render(chainSchema, version);
const differences = differencesBetween(chainSchema, baseline);

console.log(`chain:       ${chainSchema.length} objects, user_version ${version}`);
console.log(`fingerprint: ${schemaFingerprint(MIGRATIONS, version)} — what a database the chain built holds`);

if (differences.length > 0) {
  console.error(`\n✗ ${differences.length} difference(s):\n`);
  for (const line of differences) console.error(`  ${line}`);
  process.exit(1);
}
console.log(`✓ ${check ? target : "the baseline"} reproduces the chain exactly`);

if (process.argv.includes("--write")) {
  writeFileSync(target, baseline);
  console.log(`→ wrote ${target} (${baseline.length} bytes)`);
} else if (!check) {
  console.log("(dry run — pass --write to write the baseline)");
}
